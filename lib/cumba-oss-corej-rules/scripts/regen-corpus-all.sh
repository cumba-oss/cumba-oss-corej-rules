#!/usr/bin/env bash
# Six-step corpus regeneration with a per-step sentinel.
#
# ⛔ WHY THIS DERIVES ITS TREE INSTEAD OF HARD-CODING ONE (2026-08-27).
# The predecessor baked in `W=/data/net.cumba.corej-wt-retire-transforms`. After the lane's work
# was patched back into main, the script was reused unchanged: it regenerated the WORKTREE's
# corpus while the caller edited and gated MAIN. All six sentinels reported rc=0 and the log
# showed every step running — truthfully, in the wrong tree. The corpus never moved, and the
# gate went green over it. Only a round-trip test comparing rules-src against shipped rules/
# caught it.
# ⇒ A regen must target WHERE THE CALLER IS, never a path remembered from an earlier session.
set -u
usage() {
    cat >&2 <<USAGE
usage: $(basename "$0") [tree]
  Runs the SIX-step corpus regeneration, one sentinel per step, then asserts the
  shipped corpus is not stale relative to rules-src.
  tree   the repo to regenerate. Default: the git toplevel of \$PWD.
USAGE
    exit 2
}
case "${1:-}" in -h|--help) usage ;; esac
[ $# -gt 1 ] && usage

if [ $# -eq 1 ]; then
    W="$1"
else
    W="$(git rev-parse --show-toplevel 2>/dev/null)" || {
        echo "regen-corpus-all: not inside a git work tree, and no tree given — refusing to guess." >&2
        exit 2
    }
fi
[ -d "$W" ] || { echo "regen-corpus-all: no such tree: $W" >&2; exit 2; }
[ -x "$W/lib/corej-cdisc-rules/scripts/regen-rules-corpus.sh" ] || {
    echo "regen-corpus-all: $W does not look like the coreJ repo (regen-rules-corpus.sh missing/not executable)" >&2; exit 2; }

# Sentinels are namespaced by the TREE, so two trees can never share or overwrite them.
TAG="$(basename "$W")"
SENT="${SENT_DIR:-${TMPDIR:-/tmp}}/regen6-$TAG"
mkdir -p "$SENT"
export CDISC_PICKLE_CACHE_DIR="${CDISC_PICKLE_CACHE_DIR:-/data/cdisc.metadata.library-cache-pkl}"
export CDISC_API_CACHE="${CDISC_API_CACHE:-/data/cdisc.metadata.library-cache}"

echo "=== regen-corpus-all: TREE=$W   sentinels=$SENT"
cd "$W" || exit 2

step() { n="$1"; shift; echo "=== STEP $n: $* ==="; "$@"; rc=$?; echo "$rc" > "$SENT/step$n.rc"
         echo "=== STEP $n rc=$rc ==="; return $rc; }

R=lib/corej-cdisc-rules
step 1 "$R/scripts/regen-rules-corpus.sh"                     || exit 1
step 2 "$R/scripts/regen-rule-equivalence.sh"                 || exit 1
step 3 python3 "$R/documentation/rule-inventory/generate-inventory.py" || exit 1
step 4 python3 "$R/documentation/rule-inventory/build-overview.py"     || exit 1
step 5 "$R/scripts/gen-rule-doc-census.sh"                    || exit 1
step 6 "$R/scripts/gen-routing-census.sh"                     || exit 1

# ⚠ rc=0 on the wrapper proves nothing. Assert the corpus actually MOVED relative to its source.
echo "=== regen-corpus-all: verifying the corpus is not stale ==="
python3 - "$W" <<'PY'
import sys, json, glob, os, subprocess
W = sys.argv[1]
os.chdir(os.path.join(W, "lib/corej-cdisc-rules"))
shipped = {}
# ⚑ target/rules, not rules/: the corpus is GENERATED by the corej-cdisc-rules build and is
# no longer committed (plans/PLAN-rules-corpus-build-integration.md). Step 1 above writes
# there. A wrong glob here returns nothing, leaves `shipped` empty, and lands every authored
# rule in `missing` -- i.e. it reports "the corpus is STALE" for a corpus that is perfect.
GENERATED = "target/rules"
if not os.path.isfile(os.path.join(GENERATED, "packages.json")):
    print(f"⛔ regen-corpus-all: no generated corpus at {GENERATED} — step 1 did not write it.")
    sys.exit(1)
for p in glob.glob(f"{GENERATED}/rules-*.json"):
    if p.endswith("packages.json"):
        continue
    for cid, r in (json.load(open(p)).get("rules") or {}).items():
        shipped.setdefault(cid, r)
src = {os.path.basename(p)[:-5] for p in glob.glob("rules-src/checks/*/*.yaml")}
parked = subprocess.run(["grep", "-rl", 'Executability: "Not Executable"', "rules-src/checks"],
                        capture_output=True, text=True).stdout.split()
parked = {os.path.basename(p)[:-5] for p in parked}
missing = sorted((src - parked) - set(shipped))
if missing:
    print(f"⛔ regen-corpus-all: {len(missing)} authored rules are NOT in shipped rules/ — the corpus is STALE.")
    print("   first:", missing[:8])
    sys.exit(1)
print(f"✅ regen-corpus-all: {len(shipped)} shipped ids cover every authored rule ({len(src)} authored, {len(parked)} parked)")
PY
