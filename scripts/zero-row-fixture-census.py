#!/usr/bin/env python3
"""Zero-row .cdt fixture census -> documentation/zero-row-fixtures.tsv (read-only over the suites).

PLAN-zero-row-routing-rekey.md phase 0 (b) item 1. Two detectors, BOTH named in the output so the
"84 / 87 / 36" figures are never re-derived by hand with a different definition each time:

  narrow  : the file declares exactly ONE dataset, and it has columns and zero data rows.
  primary : the fixture's `#test ... domain=D` dataset is declared with columns and zero data rows.

A fixture is listed when either detector holds. Columns:
  Core.Id  expect  domain  narrow  primary  fixture

Usage (from anywhere):
  python3 lib/corej-cdisc-rules/scripts/zero-row-fixture-census.py            # rewrites the TSV
  python3 lib/corej-cdisc-rules/scripts/zero-row-fixture-census.py --stdout   # prints instead

The summary line (narrow / primary / distinct ids / union) goes to stderr.
"""
import csv
import io
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
MODULE = HERE.parent
ROOT = (MODULE / "src" / "test" / "resources"
        / "net" / "cumba" / "cdisc" / "core" / "ruletestsuites")
OUT = MODULE / "documentation" / "zero-row-fixtures.tsv"


def parse(path):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    rid = expect = dom = None
    for ln in lines:
        m = re.match(r"#test\s+(\S+)\s+(.*)$", ln.strip())
        if m:
            rid = m.group(1)
            rest = m.group(2)
            e = re.search(r"expect=(\S+)", rest, re.I)
            expect = e.group(1) if e else None
            d = re.search(r"domain=(\S+)", rest, re.I)
            dom = d.group(1) if d else None
            break
    # datasets: name -> [ncols, nrows]. A fence is THREE OR MORE dashes (CdtFence); the closer must
    # equal the opener byte-for-byte, so a `-----` block containing a literal `---` line is one block.
    ds, cur, state, fence = {}, None, None, None
    for ln in lines:
        s = ln.strip()
        if state != "data":
            m = re.match(r"dataset\s+(\S+)", s)
            if m:
                cur = m.group(1)
                ds[cur] = [0, 0]
                state = "hdr"
                continue
        if cur is None:
            continue
        if state == "hdr" and re.match(r"col\b", s):
            ds[cur][0] += 1
            continue
        if re.fullmatch(r"-{3,}", s):
            if state == "data":
                if s == fence:
                    state = "hdr"
                    fence = None
                else:
                    ds[cur][1] += 1
            else:
                state = "data"
                fence = s
            continue
        if state == "data" and s and not s.startswith("#"):
            ds[cur][1] += 1
    return rid, expect, dom, ds


def census():
    rows = []
    for p in sorted(ROOT.rglob("*.cdt")):
        rid, expect, dom, ds = parse(p)
        if not rid:
            continue
        narrow = len(ds) == 1 and all(c > 0 and r == 0 for c, r in ds.values())
        primary = dom in ds and ds[dom][0] > 0 and ds[dom][1] == 0
        if narrow or primary:
            rows.append((rid, expect or "", dom or "", "narrow" if narrow else "",
                         "primary" if primary else "", p.relative_to(ROOT).as_posix()))
    return rows


def render(rows):
    buf = io.StringIO()
    buf.write("# Generated by scripts/zero-row-fixture-census.py. DO NOT HAND-EDIT.\n")
    buf.write("# narrow  = the file declares exactly one dataset, with columns and zero data rows\n")
    buf.write("# primary = the `#test ... domain=D` dataset is declared with columns and zero data rows\n")
    n_narrow = sum(1 for r in rows if r[3])
    n_primary = sum(1 for r in rows if r[4])
    ids = len({r[0] for r in rows})
    buf.write(f"# narrow={n_narrow} primary={n_primary} distinct-ids={ids} union={len(rows)}\n")
    w = csv.writer(buf, delimiter="\t", lineterminator="\n")
    w.writerow(["Core.Id", "expect", "domain", "narrow", "primary", "fixture"])
    for r in rows:
        w.writerow(r)
    return buf.getvalue(), (n_narrow, n_primary, ids, len(rows))


def main(argv):
    rows = census()
    text, (n_narrow, n_primary, ids, union) = render(rows)
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        OUT.write_text(text, encoding="utf-8")
    print(f"# zero-row fixtures: narrow={n_narrow} primary={n_primary} distinct-ids={ids} "
          f"union={union} -> {'stdout' if '--stdout' in argv else OUT}", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])
