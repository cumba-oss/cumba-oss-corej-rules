#!/usr/bin/env python3
"""Per-package "domain table has no records" coverage -> documentation/no-records-coverage.tsv.

PLAN-zero-row-routing-rekey.md phase 0 (b) item 3 / §3.5 — the mint list's oracle and the phase-3
acceptance check. Reads the SHIPPED packages (rules/rules-*.json, the view the engine executes) and,
for every package, lists the rules of the "no records" class:

    Operations carries an `$records_in_dataset` entry whose shipped expression is `record_count()`
    (authored `operator: record_count`), the Check is `$records_in_dataset == 0`, and
    Scope.Domains.Include is exactly [ALL].

Columns:  package  covering_ids  (empty when the package carries none)

Usage (from anywhere):
  python3 lib/corej-cdisc-rules/scripts/no-records-coverage.py            # rewrites the TSV
  python3 lib/corej-cdisc-rules/scripts/no-records-coverage.py --stdout   # prints instead

The summary (covered / uncovered, and the uncovered packages by family) goes to stderr.
"""
import io
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
MODULE = HERE.parent
RULES = MODULE / "target" / "rules"
OUT = MODULE / "documentation" / "no-records-coverage.tsv"

CHECK = re.compile(r"^\s*\$records_in_dataset\s*==\s*0\s*$")


def is_no_records_rule(rule):
    ops = rule.get("Operations") or []
    has_count = any(
        o.get("id") == "$records_in_dataset"
        and (o.get("expression", "").strip() == "record_count()" or o.get("operator") == "record_count")
        for o in ops)
    if not has_count:
        return False
    check = (rule.get("Check") or {}).get("expression", "")
    if not CHECK.match(check):
        return False
    domains = (rule.get("Scope") or {}).get("Domains") or {}
    return domains.get("Include") == ["ALL"] and not domains.get("Exclude")


def package_files():
    """The packages packages.json indexes, plus any rules-*.json it does not (reported loudly)."""
    indexed = []
    idx = RULES / "packages.json"
    if idx.exists():
        data = json.loads(idx.read_text(encoding="utf-8"))
        entries = data.get("packages", data) if isinstance(data, dict) else data
        for e in entries:
            f = e.get("file") if isinstance(e, dict) else None
            if f:
                indexed.append(RULES / f)
    on_disk = sorted(RULES.glob("rules-*.json"))
    stray = [p for p in on_disk if p not in indexed]
    if indexed and stray:
        print(f"# WARNING: {len(stray)} rules-*.json not indexed by packages.json: "
              f"{[p.name for p in stray]}", file=sys.stderr)
    return sorted(set(indexed) | set(on_disk)) if indexed else on_disk


def coverage():
    rows = []
    for p in package_files():
        pkg = p.stem[len("rules-"):]
        rules = json.loads(p.read_text(encoding="utf-8")).get("rules", {})
        ids = sorted(rid for rid, r in rules.items() if is_no_records_rule(r))
        rows.append((pkg, ids))
    return rows


def family(pkg):
    return pkg.split("-", 1)[0]


def render(rows):
    buf = io.StringIO()
    covered = [r for r in rows if r[1]]
    uncovered = [r for r in rows if not r[1]]
    buf.write("# Generated by scripts/no-records-coverage.py. DO NOT HAND-EDIT.\n")
    buf.write("# A package is covered when at least one shipped rule in it has\n")
    buf.write("#   Operations[$records_in_dataset = record_count()] + Check `$records_in_dataset == 0`"
              " + Scope.Domains.Include [ALL].\n")
    buf.write(f"# packages={len(rows)} covered={len(covered)} uncovered={len(uncovered)}\n")
    buf.write("package\tcovering_ids\n")
    for pkg, ids in rows:
        buf.write(f"{pkg}\t{','.join(ids)}\n")
    by_family = {}
    for pkg, _ in uncovered:
        by_family.setdefault(family(pkg), []).append(pkg)
    summary = (f"# no-records coverage: {len(covered)}/{len(rows)} covered, {len(uncovered)} uncovered"
               + "".join(f"; {f}: {len(v)} ({', '.join(v)})" for f, v in sorted(by_family.items())))
    return buf.getvalue(), summary


def main(argv):
    text, summary = render(coverage())
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        OUT.write_text(text, encoding="utf-8")
    print(summary, file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])
